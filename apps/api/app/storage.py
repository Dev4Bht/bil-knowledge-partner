"""Object storage for original documents.

Originals are write-once: a key is never overwritten with different bytes. Two backends share one
interface: a local filesystem store (default) and an S3-compatible store (any S3 server).
"""

import io
import os
import tempfile
from pathlib import Path
from typing import Protocol

from .config import Settings


class ObjectStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None: ...
    def get(self, key: str) -> bytes: ...
    def exists(self, key: str) -> bool: ...
    def check(self) -> dict: ...


def validate_key(key: str) -> str:
    """Object keys are generated by the server, but validate anyway to rule out path traversal."""
    if not key or key.startswith("/") or "\\" in key or "\x00" in key:
        raise ValueError(f"invalid object key: {key!r}")
    if any(part in ("", ".", "..") for part in key.split("/")):
        raise ValueError(f"invalid object key: {key!r}")
    return key


class LocalFileStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / validate_key(key)).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"object key escapes the store: {key!r}")
        return path

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        path = self._path(key)
        if path.exists():
            if path.read_bytes() != data:
                raise FileExistsError(f"refusing to overwrite original: {key}")
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(dir=path.parent)
        try:
            with os.fdopen(fd, "wb") as tmp:
                tmp.write(data)
            os.replace(tmp_name, path)  # atomic: readers never see a partial file
        finally:
            if os.path.exists(tmp_name):
                os.unlink(tmp_name)

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def check(self) -> dict:
        try:
            fd, name = tempfile.mkstemp(dir=self.root)
            os.close(fd)
            os.unlink(name)
            return {"ok": True, "backend": "filesystem"}
        except Exception as exc:
            return {"ok": False, "backend": "filesystem", "detail": f"{type(exc).__name__}: {exc}"}


class S3ObjectStore:
    """Any S3-compatible server (the `minio` client library speaks the S3 API)."""

    def __init__(self, settings: Settings):
        from minio import Minio

        self.bucket = settings.s3_bucket
        self.client = Minio(settings.s3_endpoint, access_key=settings.s3_access_key,
                            secret_key=settings.s3_secret_key, secure=settings.s3_secure)

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        validate_key(key)
        if self.exists(key):
            if self.get(key) != data:
                raise FileExistsError(f"refusing to overwrite original: {key}")
            return
        self.client.put_object(self.bucket, key, io.BytesIO(data), len(data), content_type=content_type)

    def get(self, key: str) -> bytes:
        response = self.client.get_object(self.bucket, validate_key(key))
        try:
            return response.read()
        finally:
            response.close()
            response.release_conn()

    def exists(self, key: str) -> bool:
        from minio.error import S3Error

        try:
            self.client.stat_object(self.bucket, validate_key(key))
            return True
        except S3Error as exc:
            if exc.code in ("NoSuchKey", "NoSuchObject"):
                return False
            raise

    def check(self) -> dict:
        try:
            if not self.client.bucket_exists(self.bucket):
                self.client.make_bucket(self.bucket)
            return {"ok": True, "backend": "s3"}
        except Exception as exc:
            return {"ok": False, "backend": "s3", "detail": f"{type(exc).__name__}: {exc}"}


def build_object_store(settings: Settings) -> ObjectStore:
    if settings.object_store_backend == "s3":
        return S3ObjectStore(settings)
    return LocalFileStore(settings.object_store_path)
