"""English <-> Dzongkha translation with a dedicated model (NLLB-200), not the chat LLM.

An 8B general chat model produced degenerate repeating syllables when asked for Dzongkha (tested 2026-11-10), so
Dzongkha text is never generated by it. NLLB-200 lists Dzongkha (dzo_Tibt). Its weights are licensed CC-BY-NC 4.0:
fine for this hackathon prototype, NOT for commercial deployment (docs/decisions.md).
Output is always a draft that needs human validation.
"""

import gc
import os
import re
import threading
from typing import Protocol

IDLE_UNLOAD_SECONDS = float(os.environ.get("NLLB_IDLE_SECONDS", "600"))  # free ~2.4 GB when nobody is translating
CPU_THREADS = int(os.environ.get("NLLB_THREADS", "4"))                    # leave the rest of the machine responsive

EN, DZ = "eng_Latn", "dzo_Tibt"
TIBETAN_DIGITS = str.maketrans("༠༡༢༣༤༥༦༧༨༩", "0123456789")
_TIBETAN = re.compile(r"[\u0F00-\u0FFF]")


class Translator(Protocol):
    def available(self) -> bool: ...
    def translate(self, text: str, source: str, target: str) -> str: ...


def western_digits(text: str) -> str:
    return text.translate(TIBETAN_DIGITS)


def tibetan_share(text: str) -> float:
    letters = [ch for ch in text if not ch.isspace() and not ch.isdigit() and ch not in ".,;:!?()-'\"།༎"]
    return (len(_TIBETAN.findall(text)) / len(letters)) if letters else 0.0


def is_degenerate(text: str) -> bool:
    """True for looping output such as the same syllable repeated, which is Tibetan script but not language."""
    syllables = [s for s in re.split(r"[་\s།༎]+", text) if s]
    if len(syllables) < 6:
        return False
    if len(set(syllables)) / len(syllables) < 0.4:
        return True
    grams = [tuple(syllables[i:i + 3]) for i in range(len(syllables) - 2)]
    return any(grams.count(g) >= 4 for g in set(grams))


class NllbTranslator:
    """Loads lazily on first use (the model is about 2.4 GB and downloads once). Thread-safe."""

    def __init__(self, model_name: str = "facebook/nllb-200-distilled-600M"):
        self.model_name = model_name
        self._lock = threading.Lock()
        self._tokenizer = None
        self._model = None
        self._idle_timer: threading.Timer | None = None

    def _unload(self) -> None:
        with self._lock:
            self._model = self._tokenizer = None
        gc.collect()

    def _touch(self) -> None:
        """Restart the idle countdown; the model is dropped from memory if it is not used again soon."""
        with self._lock:
            if self._idle_timer:
                self._idle_timer.cancel()
            self._idle_timer = threading.Timer(IDLE_UNLOAD_SECONDS, self._unload)
            self._idle_timer.daemon = True
            self._idle_timer.start()

    def available(self) -> bool:
        try:
            import torch  # noqa: F401
            import transformers  # noqa: F401
            return True
        except Exception:
            return False

    def _load(self):
        with self._lock:
            if self._model is None:
                import torch
                from transformers import AutoModelForSeq2SeqLM, AutoTokenizer

                torch.set_num_threads(CPU_THREADS)
                self._tokenizer = AutoTokenizer.from_pretrained(self.model_name)
                self._model = AutoModelForSeq2SeqLM.from_pretrained(self.model_name)
                self._device = "mps" if torch.backends.mps.is_available() else "cpu"
                self._model.to(self._device).eval()
        return self._tokenizer, self._model

    def translate(self, text: str, source: str, target: str) -> str:
        import torch

        tokenizer, model = self._load()
        tokenizer.src_lang = source
        pieces = []
        for sentence in re.split(r"(?<=[.!?])\s+|\n+", text.strip()):
            if not sentence.strip():
                continue
            batch = tokenizer(sentence, return_tensors="pt", truncation=True, max_length=200).to(self._device)
            with torch.inference_mode():
                out = model.generate(**batch, forced_bos_token_id=tokenizer.convert_tokens_to_ids(target),
                                     max_new_tokens=200, num_beams=4, no_repeat_ngram_size=3)
            pieces.append(tokenizer.batch_decode(out, skip_special_tokens=True)[0].strip())
        self._touch()
        return " ".join(pieces)


_singleton: NllbTranslator | None = None


def get_nllb(model_name: str) -> NllbTranslator:
    global _singleton
    if _singleton is None or _singleton.model_name != model_name:
        _singleton = NllbTranslator(model_name)
    return _singleton
