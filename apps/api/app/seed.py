"""Base data (always) and demo accounts plus fictional fixtures (never in production).

Run:  python -m app.seed
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from .config import Settings, get_settings
from .db import get_engine
from .demo_fixtures import FIXTURES
from .models import AccessClassification, BusinessLine, BusinessLineCode, Document, Folder, Role, User
from .security import hash_password
from .services import documents as svc
from .storage import ObjectStore, build_object_store

ROLES = ["admin", "manager", "staff"]
LINES = [("general_insurance", "General Insurance"), ("credit", "Credit"), ("pf_gf", "PF/GF"), ("corporate", "Corporate")]
FOLDERS = {
    "general_insurance": ["Handbooks", "SOPs", "Claims", "Products", "Forms"],
    "credit": ["Policy and Manuals", "Product Sheets", "Appraisal Templates", "Recovery SOPs"],
    "pf_gf": ["Scheme Rules", "Procedures", "Member FAQs"],
    "corporate": ["Circulars", "Forms", "Training"],
}
DEMO_USERS = [
    ("admin@demo.bil.test", "Demo Admin", "admin"),
    ("manager@demo.bil.test", "Demo Manager", "manager"),
    ("staff@demo.bil.test", "Demo Staff", "staff"),
]


def ensure_base_data(db: Session) -> None:
    """Roles, the four business lines and the standard folder tree. Safe to run repeatedly."""
    for name in ROLES:
        if db.execute(select(Role).where(Role.name == name)).scalar_one_or_none() is None:
            db.add(Role(name=name))
    for code, name in LINES:
        if db.execute(select(BusinessLine).where(BusinessLine.code == BusinessLineCode(code))).scalar_one_or_none() is None:
            db.add(BusinessLine(code=BusinessLineCode(code), name=name))
    db.flush()
    for code, names in FOLDERS.items():
        line = db.execute(select(BusinessLine).where(BusinessLine.code == BusinessLineCode(code))).scalar_one()
        for name in names:
            exists = db.execute(select(Folder).where(Folder.name == name, Folder.parent_id.is_(None),
                                                     Folder.business_line_id == line.id)).first()
            if not exists:
                db.add(Folder(name=name, business_line_id=line.id))
    db.commit()


def demo_allowed(settings: Settings) -> bool:
    return settings.seed_demo and settings.app_env != "production" and bool(settings.demo_password)


def seed_demo(db: Session, store: ObjectStore, settings: Settings) -> None:
    if not demo_allowed(settings):
        raise RuntimeError("Demo seeding needs SEED_DEMO=true, DEMO_PASSWORD set, and APP_ENV not production")
    for email, display_name, role_name in DEMO_USERS:
        if db.execute(select(User).where(User.email == email)).scalar_one_or_none() is None:
            role = db.execute(select(Role).where(Role.name == role_name)).scalar_one()
            db.add(User(email=email, display_name=display_name, password_hash=hash_password(settings.demo_password),
                        roles=[role]))
    db.commit()
    admin = db.execute(select(User).where(User.email == "admin@demo.bil.test")).scalar_one()

    max_bytes = settings.max_upload_mb * 1024 * 1024
    for fixture in FIXTURES:
        line = db.execute(select(BusinessLine).where(BusinessLine.code == BusinessLineCode(fixture["line"]))).scalar_one()
        folder = db.execute(select(Folder).where(Folder.name == fixture["folder"], Folder.business_line_id == line.id,
                                                 Folder.parent_id.is_(None))).scalar_one()
        if db.execute(select(Document).where(Document.title == fixture["title"], Document.folder_id == folder.id)).first():
            continue
        first, *rest = fixture["versions"]
        document = svc.create_document(
            db, store, admin, title=fixture["title"], description=fixture["description"],
            business_line=BusinessLineCode(fixture["line"]), folder_id=folder.id,
            classification=AccessClassification(fixture["classification"]), access_role_names=fixture["roles"],
            is_demo_fixture=True, filename=fixture["filename"], data=first["text"].encode(), max_bytes=max_bytes,
            label=first["label"], effective_from=first["effective_from"], effective_to=None, language="en",
            lineage="Fictional demo fixture generated by this project",
        )
        if first["approve"]:
            svc.approve_version(db, admin, document.id, document.versions[0].id)
        for item in rest:
            version = svc.add_version(
                db, store, admin, document.id, filename=fixture["filename"], data=item["text"].encode(),
                max_bytes=max_bytes, label=item["label"], effective_from=item["effective_from"], effective_to=None,
                language="en", lineage="Fictional demo fixture generated by this project",
            )
            if item["approve"]:
                svc.approve_version(db, admin, document.id, version.id)


def main() -> None:
    from sqlalchemy.orm import sessionmaker

    settings = get_settings()
    factory = sessionmaker(get_engine(), expire_on_commit=False)
    with factory() as db:
        ensure_base_data(db)
        print("Base data ready (roles, business lines, folders)")
        if demo_allowed(settings):
            seed_demo(db, build_object_store(settings), settings)
            print("Demo accounts and fictional fixtures ready")
        else:
            print("Demo seeding skipped")


if __name__ == "__main__":
    main()
